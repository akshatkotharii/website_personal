create or replace function public.portfolio_like_state(p_post_id bigint,p_token text) returns jsonb
language sql security definer set search_path=public as $$
 select jsonb_build_object('count',(select count(*) from public.likes where post_id=p_post_id),'liked',exists(select 1 from public.likes where post_id=p_post_id and fingerprint=p_token));
$$;
create or replace function public.portfolio_set_like(p_post_id bigint,p_token text,p_liked boolean) returns jsonb
language plpgsql security definer set search_path=public as $$
begin
 if char_length(p_token)<20 or char_length(p_token)>128 then raise exception 'Invalid visitor token'; end if;
 if p_liked then insert into public.likes(post_id,fingerprint) values(p_post_id,p_token) on conflict(post_id,fingerprint) do nothing;
 else delete from public.likes where post_id=p_post_id and fingerprint=p_token; end if;
 return public.portfolio_like_state(p_post_id,p_token);
end $$;
revoke all on function public.portfolio_like_state(bigint,text),public.portfolio_set_like(bigint,text,boolean) from public;
grant execute on function public.portfolio_like_state(bigint,text),public.portfolio_set_like(bigint,text,boolean) to anon,authenticated;

