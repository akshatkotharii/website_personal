-- Restrictive policies also constrain any older broad authenticated policies.
do $$
declare t text; operation text;
begin
 foreach t in array array['posts','experience','comments','subscribers','settings'] loop
   execute format('alter table public.%I enable row level security',t);
   foreach operation in array array['insert','update','delete'] loop
     execute format('drop policy if exists %I on public.%I','owner_'||operation,t);
     if operation='insert' and t in ('comments','subscribers') then continue; end if;
     if operation='insert' then
       execute format('create policy owner_insert on public.%I as restrictive for insert to anon,authenticated with check(public.is_portfolio_admin())',t);
     elsif operation='update' then
       execute format('create policy owner_update on public.%I as restrictive for update to anon,authenticated using(public.is_portfolio_admin()) with check(public.is_portfolio_admin())',t);
     else
       execute format('create policy owner_delete on public.%I as restrictive for delete to anon,authenticated using(public.is_portfolio_admin())',t);
     end if;
   end loop;
 end loop;
end $$;
